/// <reference types="vitest/config" />
import { defineConfig, type Plugin } from 'vite';
import { svelte } from '@sveltejs/vite-plugin-svelte';
import tailwindcss from '@tailwindcss/vite';
import { VitePWA } from 'vite-plugin-pwa';
import { fileURLToPath } from 'node:url';
import { readFileSync } from 'node:fs';
import { mockBackend } from './dev/mock-backend.ts';
import { devApi } from './dev/api-middleware.ts';

const pkg = JSON.parse(readFileSync(new URL('./package.json', import.meta.url), 'utf8'));

// Light canvas from design/tokens.css. The dark variant is set at runtime through the theme-color meta tag.
const CANVAS = '#f5f5f5';

// preload the two faces in a build, so the first paint is already Geist and Roboto Condensed (DESIGN.md section 5)
const preloadFonts = (): Plugin => ({
  name: 'preload-fonts',
  transformIndexHtml: {
    order: 'post',
    handler: (_html, ctx) =>
      Object.keys(ctx.bundle ?? {}).filter((f) => f.endsWith('.woff2')).map((f) => ({ tag: 'link', attrs: { rel: 'preload', as: 'font', type: 'font/woff2', href: `/${f}`, crossorigin: '' }, injectTo: 'head' as const })),
  },
});

// L4: a first visit opens on the landing page, a lazy chunk found only once the app has started, whose largest paint is
// the hero's phone shot, found only once the landing has. index.html preloads these on a first visit only (so the app's
// first load stays as it was, `pnpm bundle`); this gives it their built paths
const HERO_SHOT = 'src/flows/landing/shots/today.webp';
const preloadLanding = (): Plugin => ({
  name: 'preload-landing',
  transformIndexHtml: {
    order: 'post',
    handler: (html, ctx) => {
      const out = Object.values(ctx.bundle ?? {});
      const shot = out.find((a) => a.type === 'asset' && a.originalFileNames.some((f) => f.endsWith(HERO_SHOT)));
      const chunk = out.find((c) => c.type === 'chunk' && c.facadeModuleId?.endsWith('/flows/landing/Landing.svelte'));
      const list: string[][] = [['preload', `/${shot ? shot.fileName : HERO_SHOT}`, 'image']];
      if (chunk?.type === 'chunk') {
        for (const f of [chunk.fileName, ...chunk.imports]) if (!html.includes(`/${f}"`)) list.push(['modulepreload', `/${f}`]);
        for (const f of chunk.viteMetadata?.importedCss ?? []) list.push(['preload', `/${f}`, 'style']);
      }
      return html.replace('%LANDING_PRELOADS%', JSON.stringify(list));
    },
  },
});

export default defineConfig({
  plugins: [
    tailwindcss(),
    svelte(),
    preloadFonts(),
    preloadLanding(),
    mockBackend(),
    devApi(),
    VitePWA({
      // U2: a new worker takes over as soon as it has installed (skipWaiting below; this plugin sets it only when it
      // injects the register script). A worker left waiting for a message from the page stayed waiting on the owner's
      // iPhone, so "A new version is ready" came back on every reload. The page then only offers a reload (App.svelte)
      registerType: 'autoUpdate',
      injectRegister: false,
      manifest: {
        name: 'Ontrack',
        short_name: 'Ontrack',
        description: 'Calorie and training tracker',
        lang: 'en',
        dir: 'ltr',
        start_url: '/',
        scope: '/',
        display: 'standalone',
        orientation: 'portrait',
        theme_color: CANVAS,
        background_color: CANVAS,
        categories: ['health', 'fitness', 'lifestyle'],
        // generated by `pnpm icons` from design/brand/app-icon.svg (see pwa-assets.config.ts)
        icons: [
          { src: '/pwa-64x64.png', sizes: '64x64', type: 'image/png' },
          { src: '/pwa-192x192.png', sizes: '192x192', type: 'image/png' },
          { src: '/pwa-512x512.png', sizes: '512x512', type: 'image/png' },
          { src: '/maskable-icon-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      },
      workbox: {
        // L2: the app's photo gradients and their grain come along offline; the landing page's stay on the network
        globPatterns: ['**/*.{js,css,html,woff2,png,svg,ico,webmanifest}', '**/{haze,feature,grain}-*.webp'],
        // the gallery chunk exists on previews only and is never needed offline; MapLibre (S1b, about 1.6 MB with its
        // worker) loads when the map first opens, and the map needs the network for its tiles anyway
        globIgnores: ['**/Gallery-*', '**/maplibre-gl-*'],
        navigateFallback: '/index.html',
        // the Privacy and Terms pages in public/ are their own documents, never the app
        navigateFallbackDenylist: [/^\/api\//, /^\/__mock\//, /^\/(privacy|terms)\.html$/],
        cleanupOutdatedCaches: true,
        skipWaiting: true,
        // the scanner's WebAssembly reader (B1, about 1 MB) is cached the first time the scanner opens, not for everyone
        runtimeCaching: [{ urlPattern: /\/assets\/.*\.wasm$/, handler: 'CacheFirst', options: { cacheName: 'scanner', expiration: { maxEntries: 2 } } }],
      },
    }),
  ],
  define: {
    __APP_VERSION__: JSON.stringify(pkg.version),
    __BUILD_DATE__: JSON.stringify(new Date().toISOString()),
    // the component gallery at /gallery: dev server, local builds and Vercel previews, never production
    __GALLERY__: JSON.stringify(process.env.VERCEL_ENV !== 'production'),
  },
  resolve: { alias: { $lib: fileURLToPath(new URL('./src/lib', import.meta.url)) } },
  // L2: the photo gradients stay files, never data URLs inside the one stylesheet every screen loads
  build: { target: 'es2022', assetsInlineLimit: (file: string) => (file.includes('/design/gradients/') ? false : undefined) },
  test: { include: ['tests/unit/**/*.test.ts'] },
});
